async function run() {
  // 1. Get Category ID
  const { data: catData } = await supabase.from('name_list_categories').select('id').eq('name', 'បញ្ជីឈ្មោះបុណ្យផ្កា').single();
  if (!catData) {
      console.log('Category not found!');
      return;
  }
  const catId = catData.id;

  // 2. Delete existing
  await supabase.from('name_list_records').delete().eq('category_id', catId);
  console.log('Deleted old records for', catId);

  // 3. Prepare new records
  const lines = rawData.split('\n').filter(l => l.trim().length > 0);
  let recordsToInsert = [];

  for (const line of lines) {
    const parts = line.split('\t');
    if (parts.length < 3) continue;
    
    const name = parts[1].trim();
    const amountStr = parts[2].trim().replace(/,/g, '').replace(/៛/g, '');
    const amount = parseInt(amountStr, 10);
    const note = (parts[3] && parts[3].trim()) ? parts[3].trim() : null;
    
    if (!isNaN(amount)) {
       recordsToInsert.push({
         category_id: catId,
         name,
         amount,
         note
       });
    }
  }

  // 4. Insert chunks
  const chunkSize = 20;
  for (let i = 0; i < recordsToInsert.length; i += chunkSize) {
    const chunk = recordsToInsert.slice(i, i + chunkSize);
    const { error } = await supabase.from('name_list_records').insert(chunk);
    if (error) console.error('Error inserting chunk:', error);
  }
  console.log('Inserted', recordsToInsert.length, 'records.');
}

run();
